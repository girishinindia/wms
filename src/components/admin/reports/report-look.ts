export function reportLook(key: string, group: string): { color: string; icon: IconDefinition } {
  const g = GROUP_LOOK[group] ?? GROUP_LOOK.Admin!;
  return { color: g.color, icon: REPORT_ICON[key] ?? g.icon };
}
